    public static ScratchRoadmapResponse GetCuratedRoadmap(string trackId)
    {
        return trackId.ToLowerInvariant() switch
        {
            "mustalah-hadith" => BuildMustalahHadithRoadmap(),
            "bukhari-methodology" => BuildBukhariMethodologyRoadmap(),
            "ilm-rijal" => BuildIlmRijalRoadmap(),
            "usul-tafsir" => BuildUsulTafsirRoadmap(),
            "nahw-turath" => BuildNahwTurathRoadmap(),
            _ => BuildMustalahHadithRoadmap()
        };
    }

    public static bool TryGetCuratedRoadmap(string query, out ScratchRoadmapResponse roadmap)
    {
        var normalized = query.Trim().ToLowerInvariant();
        foreach (var track in CuratedTracks)
        {
            if (track.Id.Equals(normalized, StringComparison.OrdinalIgnoreCase) ||
                track.Title.Contains(query, StringComparison.OrdinalIgnoreCase) ||
                query.Contains(track.Title, StringComparison.OrdinalIgnoreCase))
            {
                roadmap = GetCuratedRoadmap(track.Id);
                return true;
            }
        }

        if (query.Contains("مصطلح") || query.Contains("حديث") || query.Contains("سند") || query.Contains("متن"))
        {
            roadmap = GetCuratedRoadmap("mustalah-hadith");
            return true;
        }
        if (query.Contains("بخاري") || query.Contains("تراجم") || query.Contains("ترجمة باب"))
        {
            roadmap = GetCuratedRoadmap("bukhari-methodology");
            return true;
        }
        if (query.Contains("رجال") || query.Contains("جرح") || query.Contains("تعديل") || query.Contains("رواة"))
        {
            roadmap = GetCuratedRoadmap("ilm-rijal");
            return true;
        }
        if (query.Contains("تفسير") || query.Contains("تدبر") || query.Contains("أصول التفسير"))
        {
            roadmap = GetCuratedRoadmap("usul-tafsir");
            return true;
        }
        if (query.Contains("نحو") || query.Contains("إعراب") || query.Contains("لغة"))
        {
            roadmap = GetCuratedRoadmap("nahw-turath");
            return true;
        }

        roadmap = null!;
        return false;
    }

