    public string BuildUserPrompt(AnalyzeQuranRequest request)
    {
        StringBuilder sb = new();

        sb.AppendLine("## المقطع القرآني المطلوب تحليله للحفظ والتدبر:");
        sb.AppendLine();

        if (request.SurahNumber.HasValue && !string.IsNullOrWhiteSpace(request.SurahName))
        {
            sb.AppendLine($"- **السورة**: رقم ({request.SurahNumber.Value}) — {request.SurahName}");
        }
        else if (request.SurahNumber.HasValue)
        {
            sb.AppendLine($"- **رقم السورة**: {request.SurahNumber.Value}");
        }
        else if (!string.IsNullOrWhiteSpace(request.SurahName))
        {
            sb.AppendLine($"- **اسم السورة**: {request.SurahName}");
        }

        if (request.StartAyah.HasValue && request.EndAyah.HasValue)
        {
            sb.AppendLine($"- **نطاق الآيات المطلوب**: من الآية {request.StartAyah.Value} إلى الآية {request.EndAyah.Value}");
        }
        else if (request.StartAyah.HasValue)
        {
            sb.AppendLine($"- **ابتداءً من الآية**: {request.StartAyah.Value}");
        }

        if (!string.IsNullOrWhiteSpace(request.CustomText))
        {
            sb.AppendLine();
            sb.AppendLine("### نص الآيات المدخل:");
            sb.AppendLine(request.CustomText.Trim());
        }

        sb.AppendLine();
        sb.AppendLine("⚠️ **توجيهات جوهرية للتدبر ومناسبات الآيات وبيان الروابط**:");
        sb.AppendLine("1. استخرج وحصر جميع الكلمات والألفاظ والتراكيب غير الواضحة في مصفوفة `vocabulary` لكل آية مع بيان معناها بأسلوب مبسط جداً.");
        sb.AppendLine("2. لكل آية: اذكر الوقفة التدبرية السلوكية (`actionableTadabbur`)، وسبب النزول إن وجد (`asbabNuzul`).");
        sb.AppendLine("3. وجه المناسبة والربط بالآية التالية (`contextWithNext`): يجب تأصيله وتعميقه وفق علم المناسبات ببدء الجملة بنمط العلاقة البلاغية والمنطقية بين قوسين معقوفين `[تفصيل/تعليل/استدلال/مقابلة/تسلية/تدرج/استئناف]` متبوعاً بالعلة التفسيرية لسر الانتقال، مع إبراز الجسر اللفظي والدلالي بين خاتمة الآية الحالية ومطلع الآية التالية، وتجنب العبارات السطحية والعامة.");
        sb.AppendLine("4. اذكر أسماء السورة وفضائلها الثابتة وخطة الحفظ المقترحة في `surahInfo`.");
        sb.AppendLine("5. استخرج المحاور الموضوعية (`thematicSections`) وجدول المتشابهات وضوابط الحفظ (`mutashabihat`).");
        sb.AppendLine("6. عند تحليل نطاق يزيد عن 15 آية، احرص على أن تكون الجمل التفسيرية والتدبرية مركزة وموجزة وبليغة لكل حقل لتفادي فرط الإطالة وضمان سلامة واكتمال بنية JSON.");
        sb.AppendLine("يرجى إعداد الدراسة التحليلية الكاملة وإرجاع كائن JSON فقط.");

        return sb.ToString();
    }
