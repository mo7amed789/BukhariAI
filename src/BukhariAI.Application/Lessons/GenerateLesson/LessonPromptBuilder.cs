    public string BuildUserPrompt(string extractedArabicText, LessonLearningContext? context = null)
    {
        StringBuilder sb = new();

        if (context is not null && HasContent(context))
        {
            sb.AppendLine("## ذاكرة الدروس السابقة (Active Lesson Learning Memory)");
            sb.AppendLine();
            sb.AppendLine("استخدم هذه الذاكرة للربط التراكمي، وتكييف الشرح بناءً على مستوى إتقان الطالب، وتجنب التكرار غير الضروري للمفاهيم المتقنة مسبقًا.");
            sb.AppendLine("المصدر الأساسي للحكم والمسائل هو النص المستخرج أدناه.");
            sb.AppendLine($"### النية التعليمية المحددة من الخلفية (Learning Intent): {context.LearningIntent}");
            sb.AppendLine("اتبع قرار الخلفية التربوي لكل مفهوم. لا تغيّر مستوى الطالب ولا تخترع دليلاً أو حكماً خارج المصدر.");
            sb.AppendLine();

            if (context.AdaptiveDecisions.Count > 0)
            {
                sb.AppendLine("### القرارات التعليمية التكيفية (BACKEND AUTHORITATIVE):");
                foreach (var d in context.AdaptiveDecisions)
                    sb.AppendLine($"- {d.ConceptKey}: Action={d.Action}; Level={d.LearningLevel}; Confidence={d.Confidence:F2}; Reason={d.Reason}; QuestionType={d.SuggestedQuestionType}");
                sb.AppendLine();
            }

            if (context.StudentMastery.Count > 0)
            {
                sb.AppendLine("### مستوى إتقان الطالب الحالي للمفاهيم (STUDENT MASTERY):");
                foreach (var sm in context.StudentMastery)
                {
                    sb.AppendLine($"- Concept: {sm.Concept}");
                    sb.AppendLine($"  Level: {sm.Level}");
                    sb.AppendLine($"  Score: {sm.Score:F2}");
                    sb.AppendLine();
                }
            }

            if (context.People.Count > 0)
            {
                sb.AppendLine("### أشخاص تم التعرف عليهم سابقًا في الدروس السابقة (لا تكرر نبذتهم كاملة إلا باقتضاب):");
                foreach (var p in context.People) sb.AppendLine($"- {p}");
                sb.AppendLine();
            }

            if (context.Terms.Count > 0)
            {
                sb.AppendLine("### مصطلحات ومفاهيم تم شرحها سابقًا (استخدمها بانسيابية دون إعادة تعريفها من الصفر إذا كانت متقنة):");
                foreach (var t in context.Terms) sb.AppendLine($"- {t}");
                sb.AppendLine();
            }

            if (context.Topics.Count > 0)
            {
                sb.AppendLine("### موضوعات ومسائل تم دراستها سابقًا:");
                foreach (var top in context.Topics) sb.AppendLine($"- {top}");
                sb.AppendLine();
            }

            if (context.KeyIdeas.Count > 0)
            {
                sb.AppendLine("### أفكار محورية وأحكام تم إثباتها سابقًا:");
                foreach (var k in context.KeyIdeas) sb.AppendLine($"- {k}");
                sb.AppendLine();
            }

            if (context.PreviousDiscussions.Count > 0)
            {
                sb.AppendLine("### ملخص استدلالات ومسائل سابقة:");
                foreach (var d in context.PreviousDiscussions) sb.AppendLine($"- {d}");
                sb.AppendLine();
            }

            if (context.EstablishedConnections.Count > 0)
            {
                sb.AppendLine("### روابط تم إثباتها سابقًا:");
                foreach (var c in context.EstablishedConnections) sb.AppendLine($"- {c}");
                sb.AppendLine();
            }

            sb.AppendLine("---");
            sb.AppendLine();
        }

        sb.AppendLine("## توجيه التحليل والشرح الملزم (Word-by-word Analysis & No Summary)");
        sb.AppendLine("قم بتحليل وشرح النص المعروض كلمة بكلمة وجملة بجملة، وفكك معاني المفردات والمسائل والعلل الفقهية واللغوية تفصيلاً مستوعباً وشاملاً لكل جزئية. ممنوع التلخيص أو الاقتصار على مجمل المعنى، واشرح كل مسألة بدقة تامة في حقل easyExplanation وبقية الحقول.");
        sb.AppendLine();
        sb.AppendLine("## النص المستخرج من الكتاب");
        sb.AppendLine();
        sb.AppendLine(extractedArabicText);
        return sb.ToString();
    }

    public string BuildVisionUserPrompt(IReadOnlyList<PageScreenshot> pages, LessonLearningContext? context = null)
    {
        string pageList = string.Join("، ", pages.Select(p => p.PageNumber));
        string contextPrompt = BuildUserPrompt("[الصور المرفقة هي المصدر؛ لا يوجد نص مستخرج محليًا.]", context);
        return $"{contextPrompt}\n\n## صفحات المصدر المرئية\nالصور المرفقة مرتبة بحسب الصفحات: {pageList}. اقرأ العناوين والمتن والأحاديث والحواشي من الصور، واشرح وحلل النص كلمة بكلمة وجملة بجملة مستوعباً كل مسألة دون أي تلخيص أو اختصار، ثم أعد JSON فقط وفق المخطط المطلوب.";
    }

    public string BuildFullPrompt(string extractedArabicText, LessonLearningContext? context = null)
    {
        return $"""
            {BuildSystemPrompt()}

            {BuildUserPrompt(extractedArabicText, context)}
            """;
    }

    private static bool HasContent(LessonLearningContext ctx) =>
        ctx.People.Count > 0 || ctx.Terms.Count > 0 || ctx.KeyIdeas.Count > 0 ||
        ctx.PreviousDiscussions.Count > 0 || ctx.EstablishedConnections.Count > 0 ||
        ctx.Topics.Count > 0 || ctx.StudentMastery.Count > 0 || ctx.AdaptiveDecisions.Count > 0;
}